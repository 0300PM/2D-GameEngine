import { describe, expect, it } from "vitest";
import {
  SqlSaveStore,
  sqlClear,
  sqlDelete,
  sqlGet,
  sqlKeys,
  sqlSchema,
  sqlSet,
  type SqlClient,
  type SqlDialect
} from "../../packages/engine/src/save/SqlSaveStore";
import * as serverSql from "../../tools/save-server/sql.mjs";

class FakeSqlClient implements SqlClient {
  readonly log: { sql: string; params: readonly unknown[] }[] = [];
  private rows = new Map<string, string>();
  private failNext: string | null = null;

  failOn(sqlPart: string): void {
    this.failNext = sqlPart;
  }

  async query<T = Record<string, unknown>>(sql: string, params: readonly unknown[] = []): Promise<{ rows: T[]; affectedRows?: number }> {
    this.log.push({ sql, params });
    if (this.failNext && sql.includes(this.failNext)) {
      this.failNext = null;
      throw new Error("connection lost");
    }
    if (sql.startsWith("SELECT entry_key")) {
      return { rows: [...this.rows.keys()].sort().map((key) => ({ entry_key: key }) as T) };
    }
    if (sql.startsWith("SELECT value")) {
      const value = this.rows.get(String(params[0]));
      return { rows: (value === undefined ? [] : [{ value }]) as T[] };
    }
    if (sql.startsWith("INSERT")) {
      this.rows.set(String(params[0]), String(params[1]));
      return { rows: [], affectedRows: 1 };
    }
    if (sql.startsWith("DELETE FROM")) {
      if (params.length === 0) {
        const count = this.rows.size;
        this.rows.clear();
        return { rows: [], affectedRows: count };
      }
      const removed = this.rows.delete(String(params[0]));
      return { rows: [], affectedRows: removed ? 1 : 0 };
    }
    return { rows: [] };
  }
}

describe("sql statements", () => {
  it("uses postgres placeholders and upsert syntax", () => {
    expect(sqlGet({ dialect: "postgres" })).toBe("SELECT value FROM b2d_entries WHERE entry_key = $1");
    expect(sqlSet({ dialect: "postgres" })).toContain("ON CONFLICT (entry_key) DO UPDATE SET value = EXCLUDED.value");
    expect(sqlDelete({ dialect: "postgres" })).toContain("$1");
    expect(sqlSchema({ dialect: "postgres" })[0]).toContain("TIMESTAMPTZ");
  });

  it("uses mysql placeholders and duplicate key syntax", () => {
    expect(sqlGet({ dialect: "mysql" })).toBe("SELECT value FROM b2d_entries WHERE entry_key = ?");
    expect(sqlSet({ dialect: "mysql" })).toContain("ON DUPLICATE KEY UPDATE value = VALUES(value)");
    expect(sqlSchema({ dialect: "mysql" })[0]).toContain("LONGTEXT");
  });

  it("quotes the configured table and rejects unsafe names", () => {
    expect(sqlKeys({ dialect: "mysql", table: "game_saves" })).toBe("SELECT entry_key FROM game_saves ORDER BY entry_key");
    expect(sqlClear({ dialect: "postgres", table: "saves" })).toBe("DELETE FROM saves");
    expect(() => sqlGet({ dialect: "postgres", table: "bad name" })).toThrow(/Invalid SQL table name/);
  });

  it("matches the SQL generated by the save server", () => {
    const dialects: SqlDialect[] = ["postgres", "mysql"];
    for (const dialect of dialects) {
      const options = { dialect, table: "b2d_entries" };
      expect(sqlSchema(options)).toEqual(serverSql.schemaStatements(dialect, "b2d_entries"));
      expect(sqlGet(options)).toBe(serverSql.selectStatement(dialect, "b2d_entries"));
      expect(sqlSet(options)).toBe(serverSql.upsertStatement(dialect, "b2d_entries"));
      expect(sqlDelete(options)).toBe(serverSql.deleteStatement(dialect, "b2d_entries"));
      expect(sqlKeys(options)).toBe(serverSql.keysStatement(dialect, "b2d_entries"));
      expect(sqlClear(options)).toBe(serverSql.clearStatement(dialect, "b2d_entries"));
    }
  });
});

describe("SqlSaveStore", () => {
  const build = (dialect: SqlDialect = "postgres") => {
    const client = new FakeSqlClient();
    const store = new SqlSaveStore(client, { dialect });
    return { client, store };
  };

  it("initialises the schema before use", async () => {
    const { client, store } = build("mysql");
    await store.init();
    expect(client.log[0].sql).toContain("CREATE TABLE IF NOT EXISTS b2d_entries");
    expect(client.log).toHaveLength(sqlSchema({ dialect: "mysql" }).length);
  });

  it("implements the SaveStore contract", async () => {
    const { store } = build();
    expect(await store.get("save:1")).toBeNull();
    await store.set("save:1", "{}");
    expect(await store.get("save:1")).toBe("{}");
    await store.set("save:2", "{}");
    expect(await store.keys()).toEqual(["save:1", "save:2"]);
    expect(await store.delete("save:1")).toBe(true);
    expect(await store.delete("save:1")).toBe(false);
    await store.clear();
    expect(await store.keys()).toEqual([]);
  });

  it("passes parameters in order", async () => {
    const { client, store } = build();
    await store.set("project:default", "{\"a\":1}");
    expect(client.log[0].params).toEqual(["project:default", "{\"a\":1}"]);
  });

  it("propagates driver errors", async () => {
    const { client, store } = build();
    client.failOn("INSERT");
    await expect(store.set("a", "b")).rejects.toThrow(/connection lost/);
  });

  it("works as a store for player saves", async () => {
    const { store } = build();
    await store.init();
    await store.set("save:p1:auto", "progress");
    expect(await store.get("save:p1:auto")).toBe("progress");
  });
});
